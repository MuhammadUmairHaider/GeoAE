"""Every evaluation of the Sinkhorn ablations next to the final (balanced, Sinkhorn) GeoAE and the residual k-means
fits (balanced; plain Lloyd with density-peaks seeds, seed 42 = the models' seed, eval_out/paper_plain_kmeans_grid.py) and
the plain token-removed fit (the same Lloyd fit on x - b[token], GeoAE's subtraction without the encoder). Llama-3.2-3B layer 27, d = 6,144, K = 2,000, token bypass; all from result files, same code and
settings for every column (token_structure: 500k held-out rows; probes: probe_chance_corrected on cache_ids;
geometry: clustering_quality on 1M rows, seed 0; MMLU: 2,000 questions, splice at layer 27).

  A  no Sinkhorn, density-peaks init, re-seeding on                           (..._nosinkhorn.yaml, 50 epochs)
  B  no Sinkhorn, plain Lloyd init at epoch 11, no re-seeding, EMA centres   (..._nosinkhorn_lloyd_noreinit.yaml, 50)
The frozen-codebook run C (B with the centres never updated) is in this directory (*_nosk_frozen*.json) but left out
of the table (user, 7 Oct).

    python eval_out/summarize_nosk.py > results/delta/nosinkhorn/README.md
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

E = Path("results/delta/d6144/evals")
N = Path("results/delta/nosinkhorn")


def j(p):
    return json.loads(Path(p).read_text())


COLS = [  # name, probe file, probe arm, token_structure file, arm, geometry file, key path, mmlu file (None = no splice)
    ("Residual k-means (balanced)", E / "probe.json", "base", E / "token_structure.json", "base", E / "cq.json", "base", None),
    ("Residual k-means (plain, new fit)", E / "probe_plain_kmeans_seed42.json", "plain_seed42",
     E / "token_structure_plain_kmeans_seed42.json", "plain_seed42", E / "plain_kmeans_grid_seed42.json",
     ("geometry", "plain_residual"), None),
    ("Token-removed k-means (plain, new fit)", E / "probe_plain_kmeans_seed42.json", "plain_tokmean_seed42",
     E / "token_structure_plain_kmeans_seed42.json", "plain_tokmean_seed42", E / "plain_kmeans_grid_seed42.json",
     ("geometry", "plain_tokmean"), None),
    ("**Final GeoAE (Sinkhorn)**", E / "probe.json", "bypass", E / "token_structure.json", "bypass", E / "cq.json", "bypass",
     E / "mmlu.json"),
    ("A: no Sinkhorn, re-seeding", N / "probe_nosk_reinit+nosk_lloyd.json", "nosk_reinit",
     N / "token_structure_nosk_reinit+nosk_lloyd.json", "nosk_reinit", N / "cq_nosk_reinit.json", "nosk_reinit",
     N / "mmlu_nosk_reinit.json"),
    ("B: Lloyd init, moving centres", N / "probe_nosk_reinit+nosk_lloyd.json", "nosk_lloyd",
     N / "token_structure_nosk_reinit+nosk_lloyd.json", "nosk_lloyd", N / "cq_nosk_lloyd.json", "nosk_lloyd",
     N / "mmlu_nosk_lloyd.json"),
]
TOKEN = ["surface", "pos_coarse", "pos_fine", "ner_coarse", "ner_fine"]
SEQ = ["sentiment", "sentiment_long", "subjectivity", "formality", "language", "domain", "topic4", "topic14", "topic20"]
ENT = ["ravel_country", "ravel_continent", "ravel_language", "ioi_role", "ioi_name"]

cols = []
for name, pf, pa, tf, ta, cf, ca, mf in COLS:
    P, T, Cq = j(pf), j(tf)[ta], j(cf)
    for k in (ca if isinstance(ca, tuple) else (ca,)):
        Cq = Cq[k]
    probe = {r: P[r]["arms"][pa] for r in TOKEN + SEQ + ENT}
    M = j(mf)["meta"] if mf else None
    cols.append({"name": name, "probe": probe, "ts": T, "cq": Cq, "mmlu": M})


def ci(a):
    """est + quantile(boots - mean(boots)): the bootstrap-centred interval of eval_out/atlas_nmi.ci_centered (raw
    percentiles of the boots are biased upward)."""
    b = a.get("boots")
    if not b:
        return None
    d = np.asarray(b, dtype=float) - np.mean(b)
    return a["cnmi"] + np.quantile(d, 0.025), a["cnmi"] + np.quantile(d, 0.975)


def row(label, vals, fmt="{:.3f}"):
    cells = [("—" if v is None else fmt.format(v)) for v in vals]
    print(f"| {label} | " + " | ".join(cells) + " |")


print("# Sinkhorn ablations vs the balanced GeoAE and the residual k-means fits (Llama-3.2-3B L27, d = 6,144, K = 2,000)\n")
print("Generated by `eval_out/summarize_nosk.py` from the JSON files in this directory and `results/delta/d6144/evals/`.")
print("A: no Sinkhorn, density-peaks init, re-seeding on. B: no Sinkhorn, plain Lloyd k-means on the epoch-10 latent as "
      "the initial codebook, no re-seeding, centres updated by hard EMA (decay 0.9). Plain residual k-means: Lloyd, "
      "density-peaks seeds (seed 42), no balancing; token-removed: the same on (x - mean)/std - b[token], the "
      "token table GeoAE's bypass starts from. Their geometry comes from paper_plain_kmeans_grid.py, which computes "
      "only the five indices with clustering_quality's functions on cq.json's 1M-row sample (its balanced row "
      "reproduces cq.json). Seed 0 replicates (plain_kmeans_tokmean.json, probe_plain_kmeans_dpc.json). "
      "MMLU base accuracy 56.2.\n")
print("| Evaluation | " + " | ".join(c["name"] for c in cols) + " |")
print("|---|" + "---|" * len(cols))

print("| **Faithfulness** |" + " |" * len(cols))
row("Variance explained (held-out)", [None if "fvu" not in c["ts"] else 1 - c["ts"]["fvu"] for c in cols])
row("MMLU with splice (%)", [None if c["mmlu"] is None else 100 * c["mmlu"]["recon_acc"] for c in cols], "{:.2f}")
row("MMLU change (points)", [None if c["mmlu"] is None else 100 * c["mmlu"]["delta"] for c in cols], "{:+.2f}")

print("| **Cluster geometry (1M rows)** |" + " |" * len(cols))
for k, lab, f in [("calinski_harabasz", "Calinski–Harabasz ↑", "{:.0f}"), ("separability_ratio", "Separability ↑", "{:.1f}"),
                  ("davies_bouldin", "Davies–Bouldin ↓", "{:.2f}"), ("silhouette", "Silhouette ↑", "{:+.4f}"),
                  ("dunn_index", "Dunn ↑", "{:.4f}"), ("inter_centroid_dist_min", "Min centroid distance", "{:.3f}"),
                  ("inter_centroid_dist_mean", "Mean centroid distance", "{:.2f}"),
                  ("intra_cluster_var", "Within-cluster variance", "{:.3f}"), ("effective_k", "Effective K", "{:.0f}"),
                  ("effective_rank", "Centroid effective rank", "{:.1f}"), ("n_empty_clusters", "Empty clusters", "{:.0f}")]:
    row(lab, [c["cq"].get(k) for c in cols], f)

print("| **Usage and token structure (500k held-out rows)** |" + " |" * len(cols))
row("Clusters used", [c["ts"]["live"] for c in cols], "{:.0f}")
row("Share of the 10 largest", [100 * c["ts"]["top10"] for c in cols], "{:.1f}%")
row("Usage entropy (normalised)", [c["ts"]["usage_H"] for c in cols])
row("Current-token cNMI ↓", [c["ts"]["cnmi_cur"] for c in cols])
row("Next-token cNMI", [c["ts"]["cnmi_next"] for c in cols])
row("Clusters ≥80% one current token", [100 * c["ts"]["trivial_cur_80"] for c in cols], "{:.1f}%")
row("Clusters ≥50% one current token", [100 * c["ts"]["trivial_cur_50"] for c in cols], "{:.1f}%")
row("Clusters ≥80% one next token", [100 * c["ts"]["trivial_next_80"] for c in cols], "{:.1f}%")

for title, rungs in [("Token-level probes (chance-corrected NMI)", TOKEN), ("Sequence-level probes", SEQ),
                     ("Entity and relation probes", ENT)]:
    print(f"| **{title}** |" + " |" * len(cols))
    for r in rungs:
        row(r, [c["probe"][r]["cnmi"] for c in cols])
    row(f"mean of {len(rungs)}", [np.mean([c["probe"][r]["cnmi"] for r in rungs]) for c in cols])
row("sequence mean without language", [np.mean([c["probe"][r]["cnmi"] for r in SEQ if r != "language"]) for c in cols])

print("\n95% bootstrap intervals (sequence rungs; bootstrap-centred):\n")
print("| Probe | " + " | ".join(c["name"] for c in cols) + " |")
print("|---|" + "---|" * len(cols))
for r in SEQ:
    cells = []
    for c in cols:
        a = c["probe"][r]
        iv = ci(a)
        cells.append(f"{a['cnmi']:.3f}" + (f" [{iv[0]:.3f}, {iv[1]:.3f}]" if iv else ""))
    print(f"| {r} | " + " | ".join(cells) + " |")

# The plain fit at the other seed: which rungs move with the density-peaks seed (same code, seed 0).
P0, P0t, P42 = (j(E / "probe_plain_kmeans_dpc.json"), j(E / "probe_plain_kmeans_tokmean.json"),
                j(E / "probe_plain_kmeans_seed42.json"))
print("\nPlain k-means, seed 0 vs seed 42 (chance-corrected NMI; rungs that move by more than 0.03 are seed noise):\n")
print("| Probe | residual seed 0 | residual seed 42 | difference | token-removed seed 0 | token-removed seed 42 | difference |")
print("|---|---|---|---|---|---|---|")
for r in TOKEN + SEQ + ENT:
    a, b = P0[r]["arms"]["plain_dpc"]["cnmi"], P42[r]["arms"]["plain_seed42"]["cnmi"]
    c, d = P0t[r]["arms"]["plain_tokmean"]["cnmi"], P42[r]["arms"]["plain_tokmean_seed42"]["cnmi"]
    print(f"| {r} | {a:.3f} | {b:.3f} | {b - a:+.3f} | {c:.3f} | {d:.3f} | {d - c:+.3f} |")
