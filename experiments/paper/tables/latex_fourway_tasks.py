"""Per-task four-way probe tables (last layers), as Markdown and LaTeX, straight from the probe JSONs.

Spaces: plain residual k-means, plain token-removed k-means, bypass AE (GeoAE), no-bypass AE. Scores: raw homogeneity /
completeness / NMI on the fixed-point subset common_fp6 (rows whose cluster holds > 5 kept rows in all four spaces),
with the share of rows kept.

    python experiments/paper/tables/latex_fourway_tasks.py md  > results/delta/four_way_tasks.md
    python experiments/paper/tables/latex_fourway_tasks.py tex > docs/paper/drafts/table_fourway_tasks.tex
"""

from geoae.paths import resolve_input_path
import json
import sys

MODELS = [("Llama-3.2-3B, layer 27", "results/delta/d6144_nobypass/evals/probe_dense_subsets.json", "llama"),
          ("Gemma~3 4B, layer 33", "results/delta/g4b_l33_nobypass/evals/probe_dense_subsets.json", "gemma")]
ARMS = ["res_plain", "tok_plain", "geoae", "nobypass"]
HEAD = ["Resid. $k$-means", "Tok.-rem. $k$-means", "Bypass AE", "No-bypass AE"]
GROUPS = [
    ("Token-level", [("surface", "Surface form (7)"), ("pos_coarse", "Part of speech, coarse (12)"),
                     ("pos_fine", "Part of speech, Penn (44)"), ("ner_coarse", "Entity type, coarse (9)"),
                     ("ner_fine", "Entity type, fine (67)")]),
    ("Sequence-level", [("sentiment", "Sentiment, SST-2 (2)"), ("sentiment_long", "Sentiment, IMDB (2)"),
                        ("subjectivity", "Subjectivity (2)"), ("formality", "Formality (3)"),
                        ("language", "Language (20)"), ("domain", "Domain: code / math / prose (3)"),
                        ("topic4", "Topic, AG News (4)"), ("topic14", "Topic, DBpedia-14 (14)"),
                        ("topic20", "Topic, 20 Newsgroups (20)")]),
    ("Entity and relation", [("ravel_country", "RAVEL country"), ("ravel_continent", "RAVEL continent"),
                             ("ravel_language", "RAVEL language"), ("ioi_role", "IOI role (3)"),
                             ("ioi_name", "IOI name")]),
]
SUB = "common_fp6"
mode = sys.argv[1] if len(sys.argv) > 1 else "md"


def f3(x):
    s = f"{x:.3f}"
    return s.replace("0.", ".", 1) if x >= 0 else "$-$" + s[1:].replace("0.", ".", 1)


for title, path, key in MODELS:
    R = json.load(open(resolve_input_path(path)))["rungs"]
    if mode == "md":
        print(f"\n## {title.replace('~', ' ')}\n\nraw homogeneity / completeness / **NMI**; rows kept = rows whose cluster "
              f"holds > 5 kept rows in all four spaces\n")
        print("| Task | rows kept | " + " | ".join(h.replace("$", "") for h in HEAD) + " |")
        print("|---|---|" + "---|" * len(ARMS))
        for grp, tasks in GROUPS:
            print(f"| **{grp}** | |" + " |" * len(ARMS))
            for r, name in tasks:
                x = {a: R[r]["arms"][a][SUB] for a in ARMS}
                kept = 100 * x[ARMS[0]]["n"] / R[r]["n"]
                print(f"| {name} | {kept:.0f}% | " + " | ".join(
                    f"{x[a]['homogeneity']:.3f} / {x[a]['completeness']:.3f} / **{x[a]['nmi']:.3f}**" for a in ARMS) + " |")
        continue
    print(f"% {title}: {path}, subset {SUB} (generated by experiments/paper/tables/latex_fourway_tasks.py)")
    print("\\begin{table*}[t]\n  \\centering\n  \\scriptsize\n  \\setlength{\\tabcolsep}{2.5pt}")
    print("  \\begin{tabular}{@{}lr" + " ccc" * len(ARMS) + "@{}}\n    \\toprule")
    print("    & & " + " & ".join(f"\\multicolumn{{3}}{{c}}{{{h}}}" for h in HEAD) + " \\\\")
    print("    " + " ".join(f"\\cmidrule(lr){{{3 + 3 * i}-{5 + 3 * i}}}" for i in range(len(ARMS))))
    print("    Task & Kept & " + " & ".join(["H & C & NMI"] * len(ARMS)) + " \\\\\n    \\midrule")
    for gi, (grp, tasks) in enumerate(GROUPS):
        if gi:
            print("    \\midrule")
        print(f"    \\multicolumn{{{2 + 3 * len(ARMS)}}}{{@{{}}l}}{{\\emph{{{grp}}}}} \\\\")
        for r, name in tasks:
            x = {a: R[r]["arms"][a][SUB] for a in ARMS}
            kept = 100 * x[ARMS[0]]["n"] / R[r]["n"]
            cells = []
            for a in ARMS:
                cells += [f3(x[a]["homogeneity"]), f3(x[a]["completeness"]), f3(x[a]["nmi"])]
            print(f"    \\quad {name} & {kept:.0f}\\% & " + " & ".join(cells) + " \\\\")
    print("    \\bottomrule\n  \\end{tabular}")
    print(f"  \\caption{{Probe scores per task, {title} ($K = 2{{,}}000$). H: homogeneity, C: completeness, NMI: their harmonic "
          f"mean (no chance correction), on the rows whose cluster holds more than five rows in all four spaces (Kept). "
          f"Resid. / Tok.-rem.: plain $k$-means on the residual stream / after subtracting each token's mean vector. "
          f"Class counts in brackets.}}")
    print(f"  \\label{{tab:tasks-{key}}}\n\\end{{table*}}\n")
